//! Write a SHA-256 digest as the lowercase hexadecimal text the declarations use.

use sha2::{Digest, Sha256};

/// Return the lowercase hexadecimal SHA-256 of whole bytes.
pub fn sha256_hex(raw: &[u8]) -> String {
    Sha256::digest(raw)
        .iter()
        .map(|byte| format!("{byte:02x}"))
        .collect()
}
