#[test]
fn every_schema_pattern_matches_as_python_searches() {
    for &(pattern, text, expected) in PYTHON_CASES {
        let compiled = Pattern::compile(pattern).expect("supported pattern");
        assert_eq!(compiled.search(text), expected, "{pattern} on {text:?}");
    }
}

#[test]
fn syntax_outside_the_subset_is_refused() {
    for pattern in [
        "(a|b",
        "a|b)",
        ".",
        "*a",
        "a{",
        "a{x}",
        "a{3,2}",
        "a{,2}",
        "a{+1}",
        "[a",
        "[]",
        "[^a]",
        "[\\d]",
        "[z-a]",
        "[a-\\d]",
        "\\w",
        "(a",
        "a)",
        "^*",
        "$+",
        "]",
        "}",
        "[a-[]",
        "a{99999999999999999999999}",
    ] {
        assert_eq!(
            Pattern::compile(pattern),
            Err(format!("Unsupported schema pattern {pattern}.")),
            "{pattern}"
        );
    }
}

#[test]
fn groups_ranges_and_bounds_compose() {
    let pattern = Pattern::compile("^(a[b-d]?){2,3}-$").expect("supported pattern");
    for (text, expected) in [
        ("aa-", true),
        ("abad-", true),
        ("aaa-", true),
        ("aaaa-", false),
        ("a-", false),
        ("ae-", false),
        ("aa-\n", true),
    ] {
        assert_eq!(pattern.search(text), expected, "{text:?}");
    }
    assert!(
        Pattern::compile("[-a]")
            .expect("leading hyphen")
            .search("-")
    );
    assert!(
        Pattern::compile("[a-]")
            .expect("trailing hyphen")
            .search("-")
    );
}

#[test]
fn an_empty_group_iteration_ends_the_repetition() {
    let pattern = Pattern::compile("^(a?)*$").expect("supported pattern");
    for (text, expected) in [("aa", true), ("", true), ("b", false), ("aab", false)] {
        assert_eq!(pattern.search(text), expected, "{text:?}");
    }
}

#[test]
fn digits_and_escaped_dots_follow_python() {
    let version = Pattern::compile(r"^\d+\.\d+\.\d+$").expect("version pattern");
    for (text, expected) in [
        ("1.2.3", true),
        ("10.20.30\n", true),
        ("\u{661}.\u{6f2}.\u{966}", true),
        ("1.2", false),
        ("1x2.3", false),
        ("\u{b2}.1.1", false),
        ("1.2.3 ", false),
    ] {
        assert_eq!(version.search(text), expected, "{text:?}");
    }
}
